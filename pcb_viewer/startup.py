"""Check desktop requirements before Qt can abort inside QApplication."""
import argparse
import ctypes
import json
import os
import sys
from pathlib import Path


def desktop_error():
    if not sys.platform.startswith('linux'):
        return None
    platform = os.environ.get('QT_QPA_PLATFORM', '').split(':')[0]
    if platform in ('offscreen', 'minimal', 'vnc'):
        return None
    errors = []
    if not os.environ.get('DISPLAY') and not os.environ.get('WAYLAND_DISPLAY'):
        errors.append('No desktop display found (DISPLAY / WAYLAND_DISPLAY is unset).\n'
                      'Run from a desktop terminal or configure remote display forwarding.\n'
                      'For automated testing only: QT_QPA_PLATFORM=offscreen.')
    if platform == 'xcb' or (not platform and not os.environ.get('WAYLAND_DISPLAY')):
        missing = []
        for library in ('libxcb-cursor.so.0', 'libxcb-icccm.so.4', 'libxcb-util.so.1',
                        'libxcb-image.so.0', 'libxcb-keysyms.so.1', 'libxcb-render-util.so.0'):
            try:
                ctypes.CDLL(library)
            except OSError:
                missing.append(library)
        if missing:
            errors.append('Missing Qt XCB libraries: '+', '.join(missing)+'\n'
                          'Ubuntu/Debian: sudo apt-get install libxcb-cursor0 libxcb-icccm4 '
                          'libxcb-util1 libxcb-image0 libxcb-keysyms1 libxcb-render-util0')
    return '\n\n'.join(errors) or None


def main():
    parser = argparse.ArgumentParser(description='PCB JSON viewer and editor')
    parser.add_argument('file', nargs='?', help='PCB JSON file')
    parser.add_argument('--diagnose', action='store_true', help='Check GUI startup dependencies without opening a window')
    parser.add_argument('--autoroute', action='store_true', help='Route the input JSON without opening the GUI')
    parser.add_argument('--output', help='Autorouter output JSON (default: INPUT-routed.json)')
    parser.add_argument('--grid', type=float, default=2.0, help='Autorouter grid spacing (default: 2.0)')
    parser.add_argument('--clearance', type=float, help='Override metadata design-rule clearance')
    parser.add_argument('--iterations', type=int, default=6, help='Search-and-repair passes (default: 6)')
    args = parser.parse_args()
    if args.autoroute:
        if not args.file or not Path(args.file).is_file():
            print(f'File not found: {args.file or "(missing input)"}', file=sys.stderr)
            return 1
        try:
            from .model import Document
            from .router import RouterConfig, autoroute_data
            document = Document.load(args.file)
            # A rerun replaces only traces generated by this router.
            document.data['wires'] = [wire for wire in document.data.get('wires', [])
                                      if wire.get('route_type') != 'autoroute']
            config = RouterConfig(grid_step=args.grid, clearance=args.clearance,
                                  iterations=args.iterations)
            def progress(done, total, message):
                if done == total or done % 20 == 0:
                    print(f'[{done}/{total}] {message}', file=sys.stderr)
                return True
            wires, report = autoroute_data(document.data, config, progress)
            start = len(document.data.get('wires', []))
            document.batch_change(('wires', start + index, wire) for index, wire in enumerate(wires))
            document.data['autoroute_report'] = report.to_dict()
            source = Path(args.file)
            output = Path(args.output) if args.output else source.with_name(source.stem + '-routed.json')
            document.save(output)
            print(json.dumps({'output': str(output), **report.to_dict()}, ensure_ascii=False, indent=2))
            return 0 if report.clean else 2
        except (OSError, ValueError, TypeError, KeyError) as error:
            print(f'Autoroute failed: {error}', file=sys.stderr)
            return 1
    error = desktop_error()
    try:
        import PySide6
    except ImportError:
        error = (error+'\n\n' if error else '')+'PySide6 is not installed for this Python. Run: python -m pip install -r requirements.txt'
    if error:
        print(error, file=sys.stderr)
        return 1
    if args.diagnose:
        print('Qt desktop prerequisites found. A reachable display session is still required.')
        return 0
    if args.file and not Path(args.file).is_file():
        print(f'File not found: {args.file}', file=sys.stderr)
        return 1
    from .app import main as gui_main
    gui_main()
    return 0
